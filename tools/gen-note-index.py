"""Generate INDEX.md for the dated MBA91 notes.

The notes are the evidence log; the index is a view. Regenerate it after
adding or renaming a note:

    tools/gen-note-index.py
    tools/gen-note-index.py --check   # exit 1 if INDEX.md is stale

Status is read from an optional line near the top of a note:

    Status: live | superseded | closed — <one-line reason>

A note without one shows "—". The convention is new; retrofitting all
118 notes is not required.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

NOTES = Path(__file__).resolve().parent / "mba91-aks-macos-capture"
INDEX = NOTES / "INDEX.md"
SKIP = {"INDEX.md", "README.md", "NEXT_STEPS.md"}

DASHED = re.compile(r"(20\d{2})-(\d{2})-(\d{2})")
COMPACT = re.compile(r"(20\d{2})(\d{2})(\d{2})")


def parse_date(name: str) -> str:
    match = DASHED.search(name) or COMPACT.search(name)
    if not match:
        return ""
    year, month, day = match.groups()
    return f"{year}-{month}-{day}"


def read_note(path: Path) -> tuple[str, str]:
    title = ""
    status = ""
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for number, line in enumerate(handle):
            if number > 60:
                break
            stripped = line.strip()
            if not title and stripped.startswith("# "):
                title = stripped[2:].strip()
            elif not status and stripped.startswith("Status:"):
                status = stripped[len("Status:") :].strip()
    return title or path.stem.replace("_", " "), status


def cell(text: str, limit: int = 110) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def build() -> str:
    rows = []
    for path in sorted(NOTES.glob("*.md")):
        if path.name in SKIP:
            continue
        title, status = read_note(path)
        rows.append(
            {
                "date": parse_date(path.name),
                "name": path.name,
                "title": title,
                "status": status,
            }
        )

    # Newest dated first, then undated by name.
    dated = sorted(
        (row for row in rows if row["date"]),
        key=lambda row: (row["date"], row["name"]),
        reverse=True,
    )
    undated = sorted(
        (row for row in rows if not row["date"]), key=lambda row: row["name"]
    )

    lines = [
        "# Dated note index — MBA91",
        "",
        "Generated by [`tools/gen-note-index.py`](../../tools/gen-note-index.py).",
        "Do not edit by hand; run the generator after adding or renaming a note.",
        "",
        "The notes are the evidence log. The current narrative is",
        "[`docs/FINDINGS.md`](../../docs/FINDINGS.md), the operator standing is",
        "[`NEXT_STEPS.md`](NEXT_STEPS.md), and the merged command table is",
        "[`docs/OPCODES.md`](../../docs/OPCODES.md).",
        "",
        "`Status:` is optional and read from near the top of each note.",
        "Use `live`, `superseded` or `closed` plus a one-line reason.",
        "A dash means the note predates the convention, not that it is current.",
        "",
        f"{len(rows)} notes.",
        "",
        "| Date | Note | Title | Status |",
        "| --- | --- | --- | --- |",
    ]
    for row in dated + undated:
        lines.append(
            "| {date} | [{name}]({name}) | {title} | {status} |".format(
                date=row["date"] or "—",
                name=row["name"],
                title=cell(row["title"]),
                status=cell(row["status"]) or "—",
            )
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if INDEX.md differs from a fresh generation",
    )
    args = parser.parse_args()

    generated = build()
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""
        if current != generated:
            print("INDEX.md is stale; run tools/gen-note-index.py", file=sys.stderr)
            return 1
        print("INDEX.md is current.")
        return 0

    INDEX.write_text(generated, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(Path(__file__).resolve().parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
